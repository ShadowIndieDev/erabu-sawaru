"""えらぶの窓 さわる2択：1つのHTMLにまとめ、Swift Playgrounds用の .swiftpm と ZIP を作る。

使い方：python Tools/build.py
出力：
  docs/  … Web版（GitHub Pagesで公開する一式。iPadのアプリと同じ画面）
  build/ErabuSawaru-v<版>.swiftpm/                 … Swift Playgroundsで開くもの
  build/ErabuSawaru-playground-v<版>.zip            … iPadへ渡すZIP
"""
import base64, hashlib, json, pathlib, re, shutil, sys, zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB, NATIVE = ROOT / 'Web', ROOT / 'Native'
info = json.loads((ROOT / 'version.json').read_text(encoding='utf-8'))
VERSION, BUILD = info['version'], str(info['build'])
if not re.fullmatch(r'\d+\.\d+\.\d+', VERSION) or not BUILD.isdigit():
    sys.exit('version.json の版を確かめてください')


def read(path):
    return path.read_text(encoding='utf-8')


def page():
    html = read(WEB / 'index.html')
    css = read(WEB / 'style.css')
    scripts = []
    for name in ('logic.js', 'host.js', 'app.js'):
        js = read(WEB / name)
        if '</script' in js.lower():
            sys.exit(f'{name} に </script が含まれています')
        scripts.append(f'<script>\n{js}\n</script>')
    atlas = 'data:image/png;base64,' + base64.b64encode((WEB / 'assets' / 'choices-atlas.png').read_bytes()).decode('ascii')
    for key, value in (('/*@STYLE@*/', css), ('<!--@SCRIPTS@-->', '\n'.join(scripts)), ('@ATLAS@', atlas), ('@VERSION@', VERSION)):
        if html.count(key) != 1:
            sys.exit(f'index.html の {key} が1つではありません')
        html = html.replace(key, value)
    return html


def main():
    html = page()
    site = ROOT / 'docs'
    if site.exists():
        shutil.rmtree(site)
    site.mkdir()
    (site / 'index.html').write_text(html, encoding='utf-8', newline='\n')
    (site / '.nojekyll').write_text('', encoding='utf-8')
    for size in (180, 192, 512):
        shutil.copyfile(WEB / 'assets' / f'icon-{size}.png', site / f'icon-{size}.png')
    manifest = {'name': 'えらぶの窓 さわる2択', 'short_name': 'さわる2択', 'lang': 'ja', 'start_url': './', 'scope': './',
                'display': 'fullscreen', 'orientation': 'landscape', 'background_color': '#f2f4ee', 'theme_color': '#e4e9df',
                'icons': [{'src': f'icon-{s}.png', 'sizes': f'{s}x{s}', 'type': 'image/png'} for s in (192, 512)]}
    (site / 'manifest.webmanifest').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8', newline='\n')

    build = ROOT / 'build'
    build.mkdir(exist_ok=True)
    name = f'ErabuSawaru-v{VERSION}.swiftpm'
    pkg = build / name
    if pkg.exists():
        shutil.rmtree(pkg)
    (pkg / 'Web').mkdir(parents=True)
    package = read(NATIVE / 'Package.swift').replace('@VERSION@', VERSION).replace('@BUILD@', BUILD)
    (pkg / 'Package.swift').write_text(package, encoding='utf-8', newline='\n')
    for swift in sorted(NATIVE.glob('*.swift')):
        if swift.name != 'Package.swift':
            shutil.copyfile(swift, pkg / swift.name)
    encoded = base64.b64encode(html.encode('utf-8')).decode('ascii')
    embedded = ('// Generated by Tools/build.py; GPL-3.0-or-later\n'
                'import Foundation\n'
                'enum EmbeddedPage {\n'
                '    static var html: String? {\n'
                f'        guard let data = Data(base64Encoded: "{encoded}") else {{ return nil }}\n'
                '        return String(data: data, encoding: .utf8)\n'
                '    }\n'
                '}\n')
    (pkg / 'EmbeddedPage.swift').write_text(embedded, encoding='utf-8', newline='\n')
    (pkg / 'Web' / 'index.html').write_text(html, encoding='utf-8', newline='\n')
    for extra in ('LICENSE.txt', 'ASSET_NOTES.md'):
        shutil.copyfile(ROOT / extra, pkg / extra)

    archive = build / f'ErabuSawaru-playground-v{VERSION}.zip'
    if archive.exists():
        archive.unlink()
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        for path in sorted(pkg.rglob('*')):
            z.write(path, path.relative_to(build).as_posix())
        z.write(ROOT / 'README.md', 'README.md')
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    print(f'版 {VERSION}（build {BUILD}）')
    print(f'docs/index.html  {len(html.encode("utf-8")):,} bytes')
    print(f'{archive.relative_to(ROOT).as_posix()}  {archive.stat().st_size:,} bytes  sha256 {digest}')


if __name__ == '__main__':
    main()
